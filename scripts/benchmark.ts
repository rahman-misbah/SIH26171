// §15 benchmark driver: `npm run bench -- --label "<machine>" [--only wasm|webgpu]`.
// For each compute path it builds the e2e extension with that path forced
// (EDWARD_FORCE_COMPUTE, src/hw/detect.ts), runs tests/bench/benchmark.spec.ts
// against it, and writes both runs side by side into docs/BENCHMARKS.md
// under the operator-supplied machine label (the label is an argument, not
// a logged field -- see the M2 Log note in docs/MILESTONES.md).
//
// Plain Node script (Node 24 strips the types itself), like fetch-models.ts.

import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { renderBenchmarkSection, upsertSection, type BenchRun } from './benchmarkTable.ts';

const ROOT = path.resolve(fileURLToPath(import.meta.url), '../..');
const DOC = path.join(ROOT, 'docs/BENCHMARKS.md');
const DOC_HEADER = `# Edward — Benchmarks

Generated by \`npm run bench -- --label "<machine>"\` (SPEC §15). Each section is one machine: the
fixture pages (7 text, 3 image pages observed twice) are replayed in Chromium after warm start,
once with compute forced to WASM and once to WebGPU, and the logger's per-op p50/p95 are
reported side by side. All times are milliseconds.

Reading the tables:
- A WebGPU column only exists when Chrome exposed a real adapter (Linux needs
  \`--enable-unsafe-webgpu --enable-features=Vulkan\`, which the benchmark passes). Without one the
  run falls back to WASM and the column reads "unavailable".
- Tesseract (OCR) and zxing (QR) are WASM-only, so they run on WASM in both columns; only NER
  (ONNX Runtime) and face detection change path. MediaPipe's GPU delegate is **WebGL**, so the
  face row's WebGPU column means "the GPU path", not WebGPU itself.
- \`queue wait\` rows are time spent waiting for a free pool worker (§9.6), already included in
  the op's own time.
- \`model.load\`/\`model.warmup\` are one-off startup costs (§15 warm start), paid before the first
  task, not per observation.
`;

const { values } = parseArgs({
  options: { label: { type: 'string' }, only: { type: 'string' } },
});
if (!values.label) {
  console.error('usage: npm run bench -- --label "<machine>" [--only wasm|webgpu]');
  process.exit(2);
}
const label = values.label;
const paths = (values.only ? [values.only] : ['wasm', 'webgpu']).filter((p): p is 'wasm' | 'webgpu' => p === 'wasm' || p === 'webgpu');

function run(cmd: string, args: string[], env: Record<string, string>): boolean {
  const result = spawnSync(cmd, args, { cwd: ROOT, stdio: 'inherit', env: { ...process.env, ...env } });
  return result.status === 0;
}

const runs: BenchRun[] = [];
for (const compute of paths) {
  const out = path.join(ROOT, `.output/bench-${compute}.json`);
  const env = { EDWARD_E2E: '1', EDWARD_FORCE_COMPUTE: compute, EDWARD_BENCH_OUT: out };
  console.log(`\n=== ${compute}: build ===`);
  if (!run('npx', ['wxt', 'build'], env)) {
    console.error(`${compute}: build failed, skipping`);
    continue;
  }
  console.log(`\n=== ${compute}: replay ===`);
  if (!run('npx', ['playwright', 'test', '-c', 'playwright.bench.config.ts', 'tests/bench/benchmark.spec.ts'], env) || !existsSync(out)) {
    console.error(`${compute}: benchmark run failed, skipping`);
    continue;
  }
  runs.push(JSON.parse(await readFile(out, 'utf8')) as BenchRun);
}

if (runs.length === 0) {
  console.error('no benchmark run succeeded; docs/BENCHMARKS.md unchanged');
  process.exit(1);
}

const date = new Date().toISOString().slice(0, 10);
const section = renderBenchmarkSection(label, date, runs);
const doc = existsSync(DOC) ? await readFile(DOC, 'utf8') : DOC_HEADER;
await writeFile(DOC, upsertSection(doc, label, section));
console.log(`\n${section}\nwritten to docs/BENCHMARKS.md`);
